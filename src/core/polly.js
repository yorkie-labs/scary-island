// what Polly says to "지금 뭘 해야 해?"
export function adviceFor(state) {
  const o = currentObjective(state);
  if (!o) return ['넌 섬을 탈출했어! 정말 대단해, 깍!'];
  const lines = [`지금은 "${o.text}" 차례야.`, STEP_ADVICE[o.step.text] ?? '지도에서 ⭐ 표시를 따라가 봐!'];
  if (o.step.at) lines.push('지도(🗺️)의 ⭐ 표시가 가야 할 곳이야.');
  return lines;
}

export const metMonsters = (state) => MONSTERS.filter((m) => m.met(state));
